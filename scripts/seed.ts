/**
 * Demo Country seed generator.
 * Prints SQL that creates an invented community with invented people, places and content.
 * All content is encrypted here exactly as the app does it, so the database never sees plain text.
 *
 *   npx tsx scripts/seed.ts > supabase/seed.sql
 *
 * IMPORTANT: Demo Country is fictional. No real place, person, language or cultural knowledge is used.
 * The women's and men's items are placeholders that demonstrate the locks. Real restricted knowledge
 * must never be used in a demo.
 */
import { randomUUID } from 'node:crypto';
import * as c from '../lib/crypto';
import { eligibleRecipients, type Directory } from '../lib/access';
import { itemAd, msgAd, type Attestation, type Group, type ItemPayload, type Member, type UseKey, type UseAnswer } from '../lib/model';

const PASSWORD = 'VirtualCountry-demo-2026';
const PASSPHRASE = 'country-demo';

const q = (v: string | null | undefined) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const arr = (ids: string[]) => `array[${ids.map((i) => `'${i}'`).join(',')}]::uuid[]`;
const out: string[] = [];
const sql = (s: string) => out.push(s);

interface Person { key: string; name: string; email: string; id: string; keys: c.IdentityKeys; role: string }

function uses(over: Partial<Record<UseKey, UseAnswer>>): Record<UseKey, UseAnswer> {
  return { family: 'yes', community: 'no', school: 'no', research: 'no', government: 'no', public: 'no', ai: 'no', ...over };
}

async function main() {
  const people: Person[] = [];
  const mk = async (key: string, name: string, role: string) =>
    people.push({ key, name, role, email: `${key}.demo@example.com`, id: randomUUID(), keys: await c.newIdentity() });
  await mk('rose', 'Rose (Elder, demo)', "Elder. Founding Cultural Authority. Women's standing");
  await mk('tom', 'Tom (Elder, demo)', "Elder. Cultural Authority. Men's standing. Ranger");
  await mk('maya', 'Maya (teacher, demo)', "Teacher. Women's standing. Recovery Keeper");
  await mk('daniel', 'Daniel (Ranger, demo)', "Ranger. Men's standing");
  await mk('sam', 'Sam (administrator, demo)', 'Community Administrator. Receives no content keys');
  await mk('lee', 'Dr Lee (researcher, demo)', 'Partner organisation administrator');
  const P = Object.fromEntries(people.map((p) => [p.key, p])) as Record<string, Person>;

  const ORG = randomUUID();
  const UNI = randomUUID();

  sql('-- Demo Country seed. Generated by scripts/seed.ts. Invented data only.');
  sql('begin;');

  // ---------- auth users ----------
  for (const p of people) {
    sql(`insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, email_change, email_change_token_new, recovery_token)
values ('00000000-0000-0000-0000-000000000000', '${p.id}', 'authenticated', 'authenticated', ${q(p.email)}, extensions.crypt(${q(PASSWORD)}, extensions.gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}', ${j({ demo: true })}, now(), now(), '', '', '', '');`);
    sql(`insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values ('${randomUUID()}', '${p.id}', '${p.id}', ${j({ sub: p.id, email: p.email, email_verified: true })}, 'email', now(), now(), now());`);
  }

  // ---------- profiles, keys, vaults ----------
  for (const p of people) {
    const amk = await c.randomKey();
    const recovery = await c.newRecoveryCode();
    const identity = await c.encryptJson(amk, { encSk: p.keys.encSk, signSk: p.keys.signSk, encPk: p.keys.encPk, signPk: p.keys.signPk }, 'vc-identity-v1');
    sql(`insert into public.profiles (id, display_name) values ('${p.id}', ${q(p.name)});`);
    sql(`insert into public.public_keys (user_id, enc_pk, sign_pk) values ('${p.id}', ${q(p.keys.encPk)}, ${q(p.keys.signPk)});`);
    sql(`insert into public.vaults (user_id, amk_pin, amk_recovery, identity) values ('${p.id}', ${j(await c.wrapWithPassphrase(amk, PASSPHRASE))}, ${j(await c.wrapWithPassphrase(amk, recovery))}, ${j(identity)});`);
  }

  // ---------- organisations ----------
  sql(`insert into public.orgs (id, name, kind, founding_ca, storage_option) values ('${ORG}', 'Demo Country', 'community', '${P.rose.id}', 'cloud'), ('${UNI}', 'Demo University (partner)', 'partner', null, 'cloud');`);
  sql(`insert into public.org_settings (org_id) values ('${ORG}'), ('${UNI}');`);

  const members: Member[] = [];
  const addMember = (p: Person, org: string, admin = false, content = true) => {
    sql(`select set_config('vc.actor', '${P.sam.id}', false);`);
    sql(`insert into public.org_members (org_id, user_id, status, is_admin, content_member, approved_by, approved_at) values ('${org}', '${p.id}', 'active', ${admin}, ${content}, '${P.sam.id}', now());`);
    if (org === ORG) members.push({ user_id: p.id, display_name: p.name, is_admin: admin, content_member: content, status: 'active', enc_pk: p.keys.encPk, sign_pk: p.keys.signPk });
  };
  addMember(P.sam, ORG, true, false);
  addMember(P.rose, ORG);
  addMember(P.tom, ORG);
  addMember(P.maya, ORG);
  addMember(P.daniel, ORG);
  addMember(P.lee, UNI, true, true);

  // ---------- groups ----------
  const groups: Group[] = [];
  const addGroup = (name: string, kind: string, ms: Person[]) => {
    const g: Group = { id: randomUUID(), org_id: ORG, name, kind, members: ms.map((m) => m.id) };
    groups.push(g);
    sql(`insert into public.groups (id, org_id, name, kind) values ('${g.id}', '${ORG}', ${q(name)}, ${q(kind)});`);
    for (const m of ms) sql(`insert into public.group_members (group_id, user_id) values ('${g.id}', '${m.id}');`);
    return g;
  };
  const family = addGroup('River family (demo)', 'family', [P.rose, P.maya]);
  const rangers = addGroup('Rangers (demo)', 'rangers', [P.tom, P.daniel]);
  addGroup('School (demo)', 'school', [P.maya]);

  // ---------- attestations (signed by Cultural Authorities) ----------
  const attestations: Attestation[] = [];
  const attest = async (issuer: Person, subject: Person, claim: Attestation['claim']) => {
    const issued_at = new Date(Date.now() - 86400000 * 30).toISOString();
    const a: Attestation = { id: randomUUID(), org_id: ORG, subject_id: subject.id, claim, issuer_id: issuer.id, issued_at, sig: await c.sign(c.attestationMessage(ORG, subject.id, claim, issued_at), issuer.keys.signSk), revoked_at: null };
    attestations.push(a);
    sql(`select set_config('vc.actor', '${issuer.id}', false);`);
    sql(`insert into public.attestations (id, org_id, subject_id, claim, issuer_id, issued_at, sig) values ('${a.id}', '${ORG}', '${subject.id}', '${claim}', '${issuer.id}', ${q(issued_at)}, ${q(a.sig)});`);
  };
  await attest(P.rose, P.rose, 'standing:women');
  await attest(P.rose, P.tom, 'role:cultural_authority');
  await attest(P.tom, P.tom, 'standing:men');
  await attest(P.rose, P.maya, 'standing:women');
  await attest(P.tom, P.daniel, 'standing:men');
  await attest(P.rose, P.maya, 'role:recovery_keeper');
  await attest(P.tom, P.daniel, 'role:recovery_keeper');

  const dir: Directory = { orgId: ORG, foundingCa: P.rose.id, members, attestations, groups };

  // ---------- items ----------
  const places = {
    springs: { x: 310, y: 260, lat: -14.4512, lng: 132.2541, label: 'Seven Springs (demo)' },
    ridge: { x: 620, y: 180, lat: -14.4234, lng: 132.3012, label: 'Red Ridge (demo)' },
    creek: { x: 480, y: 420, lat: -14.4856, lng: 132.2789, label: 'Long Creek (demo)' },
    ironbark: { x: 220, y: 470, lat: -14.4912, lng: 132.2145, label: 'Ironbark Flat (demo)' },
    gorge: { x: 760, y: 330, lat: -14.4356, lng: 132.3245, label: 'Echo Gorge (demo)' },
    saltpan: { x: 650, y: 560, lat: -14.5023, lng: 132.3123, label: 'Saltpan (demo)' },
    bore: { x: 400, y: 150, lat: -14.4123, lng: 132.2654, label: 'Windmill Bore (demo)' },
  };
  const itemIds: Record<string, string> = {};

  const addItem = async (key: string, holder: Person, p: Omit<ItemPayload, 'consent' | 'media' | 'createdAt'> & { consentUses: Partial<Record<UseKey, UseAnswer>>; method?: ItemPayload['consent']['method'] }, opts: { paused?: boolean; sacred?: boolean; daysAgo?: number } = {}) => {
    const id = randomUUID();
    itemIds[key] = id;
    const createdAt = new Date(Date.now() - 86400000 * (opts.daysAgo ?? 10)).toISOString();
    const payload: ItemPayload = {
      kind: p.kind, title: p.title, body: p.body, place: p.place as any, tags: p.tags, access: p.access, restrictions: p.restrictions, labels: p.labels,
      consent: { given_by: holder.name, method: p.method ?? 'app', uses: uses(p.consentUses), recorded_at: createdAt },
      media: [], createdAt,
    };
    const recipients = await eligibleRecipients(dir, holder.id, payload, opts.paused);
    const key32 = await c.randomKey();
    const box = await c.encryptJson(key32, payload, itemAd(id, 1));
    const ctHash = await c.hashHex(box.ct);
    const rHash = await c.recipientsHash(recipients);
    const sig = await c.sign(c.itemMessage(id, 1, ctHash, rHash), holder.keys.signSk);
    sql(`select set_config('vc.actor', '${holder.id}', false);`);
    sql(`insert into public.items (id, org_id, holder_id, current_version, paused, sacred, created_at) values ('${id}', '${ORG}', '${holder.id}', 1, ${!!opts.paused}, ${!!opts.sacred}, ${q(createdAt)});`);
    sql(`insert into public.item_versions (item_id, version, nonce, ciphertext, ct_hash, recipients, recipients_hash, author_id, author_sig, created_at) values ('${id}', 1, ${q(box.nonce)}, ${q(box.ct)}, ${q(ctHash)}, ${arr(recipients)}, ${q(rHash)}, '${holder.id}', ${q(sig)}, ${q(createdAt)});`);
    for (const r of recipients) {
      const pk = people.find((x) => x.id === r)!.keys.encPk;
      sql(`insert into public.item_keys (item_id, version, recipient_id, sealed_key) values ('${id}', 1, '${r}', ${q(await c.seal(key32, pk))});`);
    }
    return id;
  };

  const none = { gender: null, sacred: false, deceased: false, season: null };

  await addItem('women', P.rose, {
    kind: 'story', title: "Women's knowledge: demo placeholder",
    body: "This is placeholder text that shows the women's lock working. Only people a Cultural Authority has confirmed as women receive the key to open it. Real women's knowledge would never be used in a demo.\n\nTry signing in as Daniel, Tom or Sam: this item will not appear for them, because their devices never receive its key.",
    place: places.springs, tags: ['water', 'demo'], access: { level: 'community' },
    restrictions: { ...none, gender: 'women' }, labels: ['tk-women', 'tk-community-use'], consentUses: { community: 'yes' },
  }, { daysAgo: 40 });

  await addItem('men', P.tom, {
    kind: 'story', title: "Men's knowledge: demo placeholder",
    body: "Placeholder text that shows the men's lock. Only people confirmed as men by a Cultural Authority can open it. Rose, Maya and Sam never receive the key.",
    place: places.ridge, tags: ['demo'], access: { level: 'community' },
    restrictions: { ...none, gender: 'men' }, labels: ['tk-men', 'tk-community-use'], consentUses: { community: 'yes' },
  }, { daysAgo: 38 });

  await addItem('springs', P.rose, {
    kind: 'observation', title: 'Checking Seven Springs in the dry season',
    body: 'Demo content. Each dry season we check how long the springs hold water. In the last three dry seasons, the two upper pools held water into late October. The lower pool dried in September. We look at the reeds, the birds that still come in, and the colour of the mud.\n\nThis observation is shared with the whole community and approved for school use. A short public summary has been signed off by a Cultural Authority.',
    place: places.springs, tags: ['water', 'dry season', 'monitoring'], access: { level: 'community' }, restrictions: none,
    labels: ['tk-attribution', 'tk-verified'], consentUses: { community: 'yes', school: 'yes', government: 'yes', public: 'yes', ai: 'yes' },
  }, { daysAgo: 30 });

  await addItem('places', P.maya, {
    kind: 'note', title: 'Place names on Demo Country (for the school)',
    body: 'Demo list for teaching. Seven Springs, Red Ridge, Long Creek, Ironbark Flat, Echo Gorge, Saltpan and Windmill Bore. In a real community, place names and their audio would be recorded with the people who hold them, in their own language.',
    place: null, tags: ['school', 'place names'], access: { level: 'community' }, restrictions: none,
    labels: ['tk-attribution'], consentUses: { community: 'yes', school: 'yes', ai: 'yes' },
  }, { daysAgo: 25 });

  await addItem('weeds', P.daniel, {
    kind: 'observation', title: 'Weed survey, Long Creek (March, demo)',
    body: 'Demo Ranger record. Buffel grass spreading along the eastern bank for about 400 m. Two patches of a thorny weed near the crossing. Recommend spraying before the wet and a repeat survey in six months. Photos and GPS track would be attached here.',
    place: places.creek, tags: ['rangers', 'weeds'], access: { level: 'group', groupId: rangers.id }, restrictions: none,
    labels: [], consentUses: { community: 'no' },
  }, { daysAgo: 20 });

  await addItem('fire', P.daniel, {
    kind: 'observation', title: 'Fire scar mapping notes 2025 (demo)',
    body: 'Demo Ranger notes. Early dry-season burns in the north-west reduced late-season fire spread. Fire scars mapped from drone imagery, compared with last year. The country near Echo Gorge recovered well after the first rain.',
    place: places.gorge, tags: ['rangers', 'fire'], access: { level: 'community' }, restrictions: none,
    labels: ['tk-attribution'], consentUses: { community: 'yes', public: 'yes', government: 'yes', ai: 'yes' },
  }, { daysAgo: 15 });

  await addItem('family', P.rose, {
    kind: 'story', title: 'Family camp at Ironbark Flat (family only, demo)',
    body: 'Demo family story. Shared only with the River family group. Other community members, the administrator and First Geospatial cannot open it.',
    place: places.ironbark, tags: ['family'], access: { level: 'group', groupId: family.id }, restrictions: none,
    labels: ['tk-community-use'], consentUses: { family: 'yes' },
  }, { daysAgo: 12 });

  await addItem('bore', P.tom, {
    kind: 'story', title: 'Fixing the old windmill bore (demo)',
    body: 'Demo story that mentions a person who has passed away. The warning is shown before anyone opens it. Talks about how the windmill was repaired years ago and how water was carted when it failed.',
    place: places.bore, tags: ['water', 'history'], access: { level: 'community' }, restrictions: { ...none, deceased: true },
    labels: ['tk-attribution'], consentUses: { community: 'yes' },
  }, { daysAgo: 9 });

  await addItem('notes', P.maya, {
    kind: 'note', title: 'My own notes (only me, demo)',
    body: 'Only Maya can open this. Not even the administrator or the platform operator can read it.',
    place: null, tags: ['personal'], access: { level: 'only_me' }, restrictions: none, labels: [], consentUses: { family: 'no' },
  }, { daysAgo: 6 });

  await addItem('sacred', P.rose, {
    kind: 'story', title: 'Ceremony ground: sacred-site flag demo',
    body: 'Demo item with the sacred-site flag. It is shared only with Tom. It can never be released publicly, exported to partners or used by the AI helper. The database refuses any release request for it.',
    place: places.saltpan, tags: ['demo'], access: { level: 'people', people: [P.tom.id] }, restrictions: { ...none, sacred: true },
    labels: ['tk-community-use'], consentUses: { community: 'no' },
  }, { sacred: true, daysAgo: 5 });

  await addItem('paused', P.rose, {
    kind: 'story', title: 'Story from a late Elder: paused for sorry business (demo)',
    body: "Demo of the sorry-business pause. This story was shared with the community, then paused. Pausing re-locked it under a new key that only Rose holds. Nobody else can open it until the family decides to lift the pause.",
    place: places.springs, tags: ['sorry business', 'demo'], access: { level: 'community' }, restrictions: { ...none, deceased: true },
    labels: [], consentUses: { community: 'yes' },
  }, { paused: true, daysAgo: 3 });

  // ---------- releases ----------
  const relPublished = randomUUID();
  {
    const title = 'Seven Springs holds water late into the dry season';
    const summary = 'Community observations over three dry seasons show the upper pools at Seven Springs holding water into late October, while the lower pool dries earlier. This summary is shared to help water planning. The detailed knowledge stays with the community.';
    const label = 'Seven Springs area (location generalised)';
    const bx = 350, by = 250;
    const bodyHash = await c.releaseBodyHash(title, summary, label, bx, by);
    const sig = await c.sign(c.releaseMessage(relPublished, bodyHash), P.rose.keys.signSk);
    sql(`select set_config('vc.actor', '${P.rose.id}', false);`);
    sql(`insert into public.releases (id, org_id, source_item_id, title, summary, place_label, blur_x, blur_y, labels, status, created_by, signer_id, sig, published_at) values ('${relPublished}', '${ORG}', '${itemIds.springs}', ${q(title)}, ${q(summary)}, ${q(label)}, ${bx}, ${by}, array['tk-attribution','tk-verified'], 'published', '${P.rose.id}', '${P.rose.id}', ${q(sig)}, now() - interval '20 days');`);
  }
  {
    sql(`select set_config('vc.actor', '${P.daniel.id}', false);`);
    sql(`insert into public.releases (org_id, source_item_id, title, summary, place_label, blur_x, blur_y, labels, status, created_by) values ('${ORG}', '${itemIds.fire}', 'Early burns reduced late-season fire spread', 'Ranger records from 2025 suggest early dry-season burning in the north-west reduced the spread of late-season fires. Shared for land-management planning, with community approval pending.', 'North-west of Demo Country (location generalised)', 750, 350, array['tk-attribution'], 'pending', '${P.daniel.id}');`);
  }

  // ---------- conversations ----------
  const addConversation = async (title: string, kind: 'group' | 'direct' | 'bridge', creator: Person, ms: Person[], msgs: [Person, string, number][], org: string | null) => {
    const id = randomUUID();
    const key = await c.randomKey();
    sql(`insert into public.conversations (id, org_id, kind, title, created_by) values ('${id}', ${org ? `'${org}'` : 'null'}, '${kind}', ${q(title)}, '${creator.id}');`);
    for (const m of ms) {
      sql(`insert into public.conversation_members (conversation_id, user_id) values ('${id}', '${m.id}');`);
      sql(`insert into public.conversation_keys (conversation_id, key_version, recipient_id, sealed_key) values ('${id}', 1, '${m.id}', ${q(await c.seal(key, m.keys.encPk))});`);
    }
    for (const [sender, text, minsAgo] of msgs) {
      const box = await c.encryptJson(key, { text }, msgAd(id));
      const sig = await c.sign(c.messageMessage(id, 1, await c.hashHex(box.ct)), sender.keys.signSk);
      sql(`insert into public.messages (conversation_id, sender_id, key_version, nonce, ciphertext, sig, created_at) values ('${id}', '${sender.id}', 1, ${q(box.nonce)}, ${q(box.ct)}, ${q(sig)}, now() - interval '${minsAgo} minutes');`);
    }
    return id;
  };
  await addConversation('Everyone in Demo Country', 'group', P.sam, [P.sam, P.rose, P.tom, P.maya, P.daniel], [
    [P.sam, 'Welcome to the Demo Country space. Everything here is invented for the demo.', 3000],
    [P.rose, 'I added the Seven Springs dry-season notes. The public summary is signed now.', 2500],
    [P.daniel, 'Weed survey from Long Creek is in the Rangers group.', 1200],
    [P.maya, 'Thank you. I will use the place names list with the school next week.', 600],
  ], ORG);
  await addConversation('Maya and Rose', 'direct', P.maya, [P.maya, P.rose], [
    [P.maya, 'Aunty, can I add the springs notes to the school collection?', 900],
    [P.rose, 'Yes, that one is fine for school. Not the family one.', 880],
  ], ORG);
  await addConversation('Rangers', 'group', P.tom, [P.tom, P.daniel], [
    [P.tom, 'Can you draft a public summary of the fire notes? I will check it before signing.', 400],
    [P.daniel, 'Done, it is waiting for your signature in Releases.', 300],
  ], ORG);

  // Bridge: the only path between organisations, through administrators, visible to members of both
  const bridgeConv = await addConversation('Demo Country and Demo University', 'bridge', P.sam, [P.sam, P.lee], [
    [P.lee, 'Hello Sam. Our water team would like to talk about access to the public Seven Springs summary for a study.', 2000],
    [P.sam, 'Thanks. I will take it to the committee. Any access would be under a signed data agreement.', 1900],
  ], null);
  sql(`select set_config('vc.actor', '${P.sam.id}', false);`);
  sql(`insert into public.bridges (org_a, org_b, conversation_id, approved_a_by, approved_b_by) values ('${ORG}', '${UNI}', '${bridgeConv}', '${P.sam.id}', '${P.lee.id}');`);

  sql(`select set_config('vc.actor', '', false);`);
  sql('commit;');

  // Demo accounts summary for the README (stderr so it does not end up in the SQL)
  console.error('\nDemo accounts (password and passphrase are the same for all):');
  console.error(`  password: ${PASSWORD}   passphrase: ${PASSPHRASE}`);
  for (const p of people) console.error(`  ${p.email.padEnd(28)} ${p.name.padEnd(28)} ${p.role}`);
  console.error(`\nDemo Country org id: ${ORG}`);

  // Written directly as UTF-8. (PowerShell's ">" would save UTF-16, which psql cannot read.)
  const target = process.argv[process.argv.indexOf('--out') + 1];
  if (process.argv.includes('--out') && target) {
    const { writeFileSync } = await import('node:fs');
    writeFileSync(target, out.join('\n') + '\n', 'utf8');
    console.error(`Wrote ${target}. Note: this makes NEW ids and keys. Reset the demo database with it, or the app and database will not match.`);
  } else process.stdout.write(out.join('\n') + '\n');
}

main().catch((e) => { console.error(e); process.exit(1); });